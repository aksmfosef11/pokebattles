import path from "node:path";
import { AUDIO_MANAGER_SRC, type AudioSourceInfo } from "./audio.ts";
import { PATHS, type Pins, tryReadJson, writeIfChanged } from "./util.ts";

/** Indents a Markdown list one level (credits lists nest under a bullet). */
const nest = (md: string) =>
  md
    .split("\n")
    .filter((l) => l.trim())
    .map((l) => `  ${l}`)
    .join("\n");

function audioSection(pins: Pins, audio: AudioSourceInfo): string {
  const c = (p: { url: string; commit: string }) => `[\`${p.commit.slice(0, 12)}\`](${p.url}/tree/${p.commit})`;
  const byLicense = new Map<string, string[]>();
  for (const f of audio.files) {
    const k = `${f.license} — ${f.copyright}`;
    byLicense.set(k, [...(byLicense.get(k) ?? []), f.repoPath.slice("audio/".length)]);
  }
  const licenseLines = [...byLicense.entries()].map(([k, files]) => `- **${k}**: ${files.map((f) => `\`${f}\``).join(", ")}`);
  return `
## Audio

Byte-identical copies of PokéRogue's own sound effects and music from [pokerogue-assets](${pins.pokerogueAssets.url}) at ${c(pins.pokerogueAssets)}
into \`apps/client/public/assets/audio/\` (same paths as below \`audio/\` in that repo), listed in \`audio/manifest.json\`.
Loop points are PokéRogue's, read from \`${AUDIO_MANAGER_SRC}\` (\`getBgmLoopPoint\`) at pokerogue ${c(pins.pokerogue)}.
Licenses per file, as that repo's \`audio/REUSE.toml\` states them:

${licenseLines.join("\n")}

The music and sound effects from the Pokémon games are © Nintendo / Creatures Inc. / GAME FREAK inc. and their composers;
PokéRogue's custom tracks belong to their authors (CC-BY-NC-SA-4.0 as noted). They are used like the sprites: unmodified, in a non-commercial fan project.

Credits, copied from PokéRogue's \`CREDITS.md\`:

- Composers (PokéRogue)
${nest(audio.composers)}
- BGM
${nest(audio.bgmCredits)}
- Sound effects
${nest(audio.seCredits)}
`;
}

/**
 * data/SOURCES.md, generated from pins.json so it always matches what was extracted. `audio` comes from
 * `pnpm sprites`; other callers (`pnpm extract`) keep the section it last wrote, which assets-manifest.json records.
 */
export function writeSourcesMd(pins: Pins, audio?: AudioSourceInfo): boolean {
  audio ??= tryReadJson<{ audio?: { sources?: AudioSourceInfo } }>(path.join(PATHS.clientAssets, "assets-manifest.json"))?.audio?.sources;
  const c = (p: { url: string; commit: string }) => `[\`${p.commit.slice(0, 12)}\`](${p.url}/tree/${p.commit})`;
  const md = `# Data & asset sources

Generated by \`tools/extract\` from \`tools/extract/pins.json\`. Every source is fetched at the exact commit below, so reruns are reproducible.
pokebattles is a **non-commercial fan project**. Pokémon, Pokémon character names, sprites and all related IP are © Nintendo / Creatures Inc. / GAME FREAK inc.; nothing here claims otherwise.

| Source | Pinned commit | What we take | License / terms as stated by that repo |
|---|---|---|---|
| [PokéRogue](${pins.pokerogue.url}) (branch \`${pins.pokerogue.ref}\`) | ${c(pins.pokerogue)} | **Data only**, read statically from \`src/\` by walking the TypeScript AST (species, forms, base stats, abilities, moves + effect attributes, learnsets, TMs, egg moves, evolutions, form changes, type chart, item/trainer key maps). No PokéRogue engine code is copied or executed. | Code is **AGPL-3.0-only** (\`LICENSE\`, \`REUSE.toml\`, © Pagefault Games). Our JSON is derived game data; if you redistribute derived files, keep this attribution and review AGPL obligations. |
| [pokerogue-locales](${pins.pokerogueLocales.url}) (${pins.pokerogueLocales.ref}) | ${c(pins.pokerogueLocales)} | Localized names/descriptions for species, forms, moves, abilities, types, natures, stats, status effects, items, trainer names/titles → \`data/i18n/*.json\` (\`_provenance\` marks every section/key). | Repo \`LICENSE\` is **AGPL-3.0**. Official Pokémon names are Nintendo/Creatures/GAME FREAK trademarks. |
| [pokerogue-assets](${pins.pokerogueAssets.url}) (${pins.pokerogueAssets.ref}) | ${c(pins.pokerogueAssets)} | Byte-identical copies into \`apps/client/public/assets/\`: Pokémon battle sprite atlases (front/back/shiny), item atlas, type icon atlases, champion trainer atlases, arena backgrounds, and a few sound effects and music tracks (see **Audio** below). | Per its README/REUSE: creative assets **CC-BY-NC-SA-4.0** "to the extent licensable" unless noted; \`images/items.png\` (and other official-art files listed in \`images/REUSE.toml\`) are **LicenseRef-FAIR-USE**, © Nintendo, Game Freak, Creatures Inc.; tool-generated atlas JSON is **AGPL-3.0-only**; PokéRogue logos are **NO-REUSE** (not copied). Credits: PokéRogue \`CREDITS.md\`. |
| [PokeAPI](${pins.pokeapi.url}) \`data/v2/csv/*.csv\` | ${c(pins.pokeapi)} | Supplemental localized names only where PokéRogue lacks them: items (e.g. Choice Band, Life Orb, Z-crystals, orbs, fossils), Z-move / Max-move names for languages PokéRogue has not translated, item flavor text for those items. Files: \`languages\`, \`items\`, \`item_names\`, \`item_flavor_text\`, \`item_categories\`, \`version_groups\`, \`moves\`, \`move_names\`. | Repo \`LICENSE.md\`: **BSD-3-Clause**, © Paul Hallett and PokéAPI contributors; "Pokémon and Pokémon character names are trademarks of Nintendo." |
| [PokeAPI/sprites](${pins.pokeapiSprites.url}) | ${c(pins.pokeapiSprites)} | Item icons missing from PokéRogue's atlas (Z-crystals, Choice Band, Life Orb, …) → \`assets/items-extra/<KEY>.png\`. | \`LICENCE.txt\`: repository distributed under **CC0 1.0**, but "All image contents within are Copyright The Pokémon Company." |

## Outputs

- \`data/pokerogue/*.json\` — \`pnpm extract\` (tools/extract/extract-pokerogue.ts); \`meta.json\` repeats the pins, \`extract-report.json\` lists anything unparseable, fallbacks and attribute histograms.
- \`data/i18n/{lang}.json\` — one file per language directory shipped by pokerogue-locales; missing strings are left missing (see each file's \`_meta.fallbackChain\`), except champion names, whose fallbacks are recorded in \`_fallbacks\`.
- \`apps/client/public/assets/**\` — \`pnpm --filter @pokebattles/tools sprites\` (tools/extract/fetch-assets.ts); manifests: \`pokemon/manifest.json\`, \`items-manifest.json\`, \`trainers/manifest.json\`, \`audio/manifest.json\`, \`assets-manifest.json\`.
${audio ? audioSection(pins, audio) : ""}`;
  return writeIfChanged(PATHS.sourcesMd, md);
}
